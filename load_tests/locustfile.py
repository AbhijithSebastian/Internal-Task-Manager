import os
import random
from locust import HttpUser, task, between

class EnterpriseUser(HttpUser):
    wait_time = between(1, 5)
    
    def on_start(self):
        # Admin credentials seeded in development DB
        self.email = "abhijith@tool.com"
        self.password = "password"
        self.token = ""
        self.project_ids = []
        self.login()
        self.setup_projects()

    def login(self):
        # API expects JSON body for LoginRequest
        response = self.client.post(
            "/api/v1/auth/login",
            json={"email": self.email, "password": self.password}
        )
        if response.status_code == 200:
            self.token = response.json().get("access_token")
            self.client.headers.update({"Authorization": f"Bearer {self.token}"})
        else:
            print(f"Login failed: {response.status_code} - {response.text}")

    def setup_projects(self):
        # Fetch existing projects to get a valid project ID
        response = self.client.get("/api/v1/projects")
        if response.status_code == 200:
            items = response.json().get("items", [])
            self.project_ids = [p["id"] for p in items]
            
        # If no projects exist, create one
        if not self.project_ids:
            proj_payload = {
                "name": "Locust Load Test Project",
                "description": "Automatically created for load testing",
                "priority": "high"
            }
            response = self.client.post("/api/v1/projects", json=proj_payload)
            if response.status_code == 201:
                pid = response.json().get("id")
                if pid:
                    self.project_ids.append(pid)
                    print(f"Created load test project with ID {pid}")
            else:
                print(f"Failed to create project: {response.status_code} - {response.text}")

    @task(5)
    def view_dashboard(self):
        self.client.get("/api/v1/projects")
        self.client.get("/api/v1/tasks")
        self.client.get("/api/v1/activity")
        
    @task(3)
    def create_task(self):
        if not self.project_ids:
            return
        project_id = random.choice(self.project_ids)
        payload = {
            "title": f"Load Test Task {random.randint(1, 999999)}",
            "description": "Generated by Locust",
            "project_id": project_id,
            "status": "todo",
            "priority": "medium"
        }
        self.client.post("/api/v1/tasks", json=payload)

    @task(1)
    def search(self):
        self.client.get(f"/api/v1/search?q=Load+Test+{random.randint(1,10)}")
